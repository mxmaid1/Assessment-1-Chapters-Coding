Age=19

if Age<=2:
    print("the person is a Baby")
elif 2<=Age<=4:
    print("the person is a toddler")
elif 4<=Age<=13:
    print("the person is a kid")
elif 13<=Age<=18:
    print("the person is a teen")
elif 18<=Age<=70:
    print("the person is a adult")
else:
    print("the person is a elder")